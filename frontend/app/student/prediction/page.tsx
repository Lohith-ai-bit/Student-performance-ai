"use client";

import { useQuery } from "@tanstack/react-query";
import { BrainCircuit, Info } from "lucide-react";
import Link from "next/link";

import { RiskBadge } from "@/components/risk-badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Skeleton } from "@/components/ui/skeleton";
import { apiGet } from "@/lib/api";
import type { PredictionRecord } from "@/types";

interface PredictionsResponse {
  success: boolean;
  latest: PredictionRecord | null;
  history: PredictionRecord[];
  disclaimer: string;
}

export default function StudentPredictionPage() {
  const { data, isLoading } = useQuery({
    queryKey: ["student-predictions"],
    queryFn: () => apiGet<PredictionsResponse>("/students/me/predictions"),
  });

  if (isLoading) {
    return (
      <div className="space-y-4">
        <Skeleton className="h-9 w-64" />
        <Skeleton className="h-64" />
      </div>
    );
  }

  const latest = data?.latest ?? null;

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div>
          <h1 className="text-2xl font-semibold tracking-tight">Performance Prediction</h1>
          <p className="mt-1 text-sm text-muted-foreground">AI-generated estimate of your final performance</p>
        </div>
        <Button variant="outline" asChild>
          <Link href="/student/prediction/history">View History</Link>
        </Button>
      </div>

      {latest ? (
        <Card className="animate-fade-up">
          <CardHeader className="items-center text-center">
            <span className="mx-auto flex h-12 w-12 items-center justify-center rounded-2xl bg-accent text-accent-foreground">
              <BrainCircuit className="h-6 w-6" />
            </span>
            <CardTitle className="mt-2">Predicted Performance</CardTitle>
          </CardHeader>
          <CardContent className="flex flex-col items-center gap-4 text-center">
            <p className="text-6xl font-bold tracking-tight text-primary">{latest.predicted_score.toFixed(1)}%</p>
            <RiskBadge level={latest.risk_level} />
            <div className="mt-2 grid w-full max-w-md grid-cols-2 gap-3 text-left text-sm">
              <div className="rounded-lg bg-secondary/60 p-3">
                <p className="text-xs text-muted-foreground">Model Used</p>
                <p className="font-medium">{latest.model_name}</p>
              </div>
              <div className="rounded-lg bg-secondary/60 p-3">
                <p className="text-xs text-muted-foreground">Model Version</p>
                <p className="font-medium">{latest.model_version}</p>
              </div>
              <div className="rounded-lg bg-secondary/60 p-3">
                <p className="text-xs text-muted-foreground">Risk Probability</p>
                <p className="font-medium">{(latest.risk_probability * 100).toFixed(1)}%</p>
              </div>
              <div className="rounded-lg bg-secondary/60 p-3">
                <p className="text-xs text-muted-foreground">Prediction Date</p>
                <p className="font-medium">{new Date(latest.prediction_date).toLocaleString()}</p>
              </div>
            </div>
            <div className="mt-2 flex w-full max-w-md items-start gap-2 rounded-lg border bg-muted/40 p-3 text-left">
              <Info className="mt-0.5 h-4 w-4 shrink-0 text-muted-foreground" />
              <p className="text-xs text-muted-foreground">{data?.disclaimer}</p>
            </div>
          </CardContent>
        </Card>
      ) : (
        <Card className="border-dashed">
          <CardContent className="flex flex-col items-center gap-2 p-10 text-center">
            <BrainCircuit className="h-8 w-8 text-muted-foreground" />
            <p className="font-medium">No prediction available yet</p>
            <p className="max-w-md text-sm text-muted-foreground">
              Predictions are generated by faculty (or automatically once enough assessment, attendance and learning
              activity data is available).
            </p>
          </CardContent>
        </Card>
      )}
    </div>
  );
}
